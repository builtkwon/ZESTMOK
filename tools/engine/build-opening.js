// Builds ai-open.js, the boss's opening book (docs/boss-ai-v2.md P4 step 1). PC only, ~1 h.
// Run: RAPFI=/path/to/pbrain-rapfi node tools/engine/build-opening.js [raw=/path/opening.jsonl] [bossNodes=2000000] [humanNodes=1000000]
//      node tools/engine/build-opening.js --emit [raw]        (raw jsonl -> ai-open.js only, no engine)
// Tree from the first black stone at the centre (the boss opens there; a human's first stone anywhere maps to it by translation):
//  - boss to move: Rapfi's best move at bossNodes (never ai.js-forbidden for black), stored in the book
//  - human to move: expand plausible replies - ply 1 = every reply within 2 cells (5 shapes up to symmetry), later Rapfi's
//    top WIDTH[ply] moves (YXNBEST at humanNodes) within SPREAD winrate of its best
// Both colours: boss-black lines (boss moves at even plies 2..12) and boss-white lines (boss moves at odd plies 1..11).
// Positions are merged up to symmetry + translation (ai.js canon), so transpositions are searched once.
// Raw rows are appended to `raw`: boss {key, move, wr, pos}, human {key, n, nb: [[move, wr]...], pos}. A rerun reuses them
// (resumable; a human row is reused only if it asked YXNBEST for at least WIDTH[ply] moves, so widening WIDTH just works).
const fs = require('fs');
const path = require('path');
const AI = require('../../ai.js');
const N = 15, args = process.argv.slice(2), emit = args[0] === '--emit';
if (emit) args.shift();
const RAW = args[0] || '/Users/green/orca/engine/data/opening.jsonl', BOSS_NODES = +args[1] || 2000000, HUMAN_NODES = +args[2] || 1000000;
const WIDTH = [0, 5, 6, 5, 4, 4, 3, 3, 3, 2, 2, 2, 2], SPREAD = 0.3, LAST = { 1: 12, 2: 11 }; // boss colour -> deepest boss ply
const OUT = path.join(__dirname, '..', '..', 'ai-open.js');

const board = (pos) => { const b = Array.from({ length: N }, () => Array(N).fill(0)); pos.forEach(([r, c], i) => b[r][c] = i % 2 ? 2 : 1); return b; };
const DIRS = [[0, 1], [1, 0], [1, 1], [1, -1]];
const wins = (b, r, c) => { const p = b[r][c]; return DIRS.some(([dr, dc]) => { let n = 1; for (const s of [1, -1]) for (let k = 1; b[r + dr * s * k] && b[r + dr * s * k][c + dc * s * k] === p; k++) n++; return p === 1 ? n === 5 : n >= 5; }); };

function writeBook() {
  const book = {};
  for (const l of fs.readFileSync(RAW, 'utf8').trim().split('\n')) { const x = JSON.parse(l); if (x.move) book[x.key] = x.move; }
  fs.writeFileSync(OUT, '// generated by tools/engine/build-opening.js - do not edit\n(typeof window !== \'undefined\' ? window : globalThis).AI_OPEN=' + JSON.stringify(book) + ';\n');
  console.log(`${Object.keys(book).length} positions, ${fs.statSync(OUT).size} bytes -> ai-open.js`);
}
if (emit) { writeBook(); process.exit(0); }

const Rapfi = require('./rapfi.js');
(async () => {
  const e = new Rapfi(); await e.start({ nodes: BOSS_NODES });
  const done = new Map(), hum = new Map(), visited = new Set(); // boss rows, human rows (cached replies), expanded this run
  if (fs.existsSync(RAW)) for (const l of fs.readFileSync(RAW, 'utf8').trim().split('\n').filter(Boolean)) { const x = JSON.parse(l); (x.move ? done : hum).set(x.key, x); }
  const out = fs.createWriteStream(RAW, { flags: 'a' });
  let n = 0;
  const legal = (b, r, c, p) => !b[r][c] && !(p === 1 && AI.forbidden(b, r, c));
  async function expand(pos, boss) {
    const ply = pos.length, p = ply % 2 ? 2 : 1, b = board(pos);
    if (ply > LAST[boss]) return;
    const k = AI.canon(b);
    if (visited.has(k.key + p + boss)) return; // transposition
    visited.add(k.key + p + boss);
    if (p === boss) {
      let row = done.get(k.key);
      if (!row) {
        e.limit({ nodes: BOSS_NODES });
        const block = [];
        let a;
        for (;;) { a = await e.best(pos, block); if (legal(b, a.move[0], a.move[1], p)) break; block.push(a.move.join(',')); }
        row = { key: k.key, move: AI.toCanon(k, a.move[0], a.move[1]), wr: a.wr, pos };
        out.write(JSON.stringify(row) + '\n'); done.set(k.key, row);
        if (++n % 50 === 0) console.log(`${n} boss positions (ply ${ply})`);
      }
      const [r, c] = AI.fromCanon(k, row.move); b[r][c] = p;
      if (!wins(b, r, c)) await expand(pos.concat([[r, c]]), boss);
      return;
    }
    let replies;
    if (ply === 1) { // every distinct reply within 2 cells of the centre stone
      const ks = new Set(); replies = [];
      for (let r = 5; r <= 9; r++) for (let c = 5; c <= 9; c++) {
        if (b[r][c]) continue;
        b[r][c] = p; const kk = AI.canon(b).key; b[r][c] = 0;
        if (!ks.has(kk)) { ks.add(kk); replies.push([r, c]); }
      }
    } else {
      let row = hum.get(k.key);
      if (!row || !(row.n >= WIDTH[ply])) {
        e.limit({ nodes: HUMAN_NODES });
        const nb = await e.nbest(pos, WIDTH[ply]);
        row = { key: k.key, n: WIDTH[ply], nb: nb.map(x => [AI.toCanon(k, x.move[0], x.move[1]), x.wr]), pos };
        hum.set(k.key, row); out.write(JSON.stringify(row) + '\n');
      }
      const nb = row.nb.map(([m, wr]) => ({ move: AI.fromCanon(k, m), wr })).sort((x, y) => y.wr - x.wr).slice(0, WIDTH[ply]);
      replies = nb.filter(x => x.wr >= nb[0].wr - SPREAD && legal(b, x.move[0], x.move[1], p)).map(x => x.move);
    }
    for (const [r, c] of replies) { b[r][c] = p; const w = wins(b, r, c); b[r][c] = 0; if (!w) await expand(pos.concat([[r, c]]), boss); }
  }
  for (const boss of [1, 2]) await expand([[7, 7]], boss);
  out.end(); e.quit();
  out.on('finish', writeBook);
})();
