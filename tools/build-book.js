// Builds ai-book.js (the boss's shared learning, loaded at boss level) from collected boss games.
// Run: BOOK_URL=<apps script url> BOOK_KEY=<key> node tools/build-book.js [seed.json ...]
//   or node tools/build-book.js --rows rows.json [seed.json ...]   (rows = the doGet output, saved to a file)
// seed = a GomokuAI.getMemory() dump (console output may stay wrapped in quotes). Setup: docs/boss-book.md
const fs = require('fs'), path = require('path');
const AI = require('../ai.js');
const N = 15;

// one collected record -> learn history, or null if it is not a legal game
function replay(rec) {
  if (!rec || ![1, 2].includes(rec.ai) || ![0, 1, 2].includes(rec.w) || !Array.isArray(rec.m) || !rec.m.length || rec.m.length > N * N) return null;
  const b = Array.from({ length: N }, () => Array(N).fill(0)), hist = [];
  for (let i = 0; i < rec.m.length; i++) {
    const [r, c] = rec.m[i] || [], p = i % 2 ? 2 : 1;
    if (!Number.isInteger(r) || !Number.isInteger(c) || r < 0 || r >= N || c < 0 || c >= N || b[r][c]) return null;
    if (p === 1 && AI.forbidden(b, r, c)) return null;
    hist.push({ p, row: r, col: c, key: AI.posKey(b, p) });
    b[r][c] = p;
  }
  return hist;
}

function parseSeed(f) {
  let t = fs.readFileSync(f, 'utf8').trim();
  if (t[0] === "'" && t.endsWith("'")) t = t.slice(1, -1); // copied from the console
  return JSON.parse(t);
}

async function rows() {
  const i = process.argv.indexOf('--rows');
  if (i > 0) { const f = process.argv.splice(i, 2)[1]; return JSON.parse(fs.readFileSync(f, 'utf8')); }
  if (!process.env.BOOK_URL) return [];
  const u = new URL(process.env.BOOK_URL); u.searchParams.set('key', process.env.BOOK_KEY || '');
  const res = await fetch(u);
  if (!res.ok) throw new Error('sheet ' + res.status);
  return res.json();
}

(async () => {
  const all = await rows(), seeds = process.argv.slice(2);
  // start from the seeds, merged (avoid = union, hum = summed counts)
  const book = { avoid: {}, hum: {} };
  for (const f of seeds) {
    const m = parseSeed(f);
    for (const k in m.avoid || {}) book.avoid[k] = [...new Set([...(book.avoid[k] || []), ...m.avoid[k]])];
    for (const k in m.hum || {}) { const e = (book.hum[k] = book.hum[k] || {}); for (const rc in m.hum[k]) { const v = m.hum[k][rc]; e[rc] = e[rc] ? [e[rc][0] + v[0], e[rc][1] + v[1]] : v.slice(); } }
  }
  AI.setMemory(book);
  const seen = new Set();
  let used = 0, bad = 0, dup = 0;
  for (const row of all) {
    let rec; try { rec = JSON.parse(Array.isArray(row) ? row[1] : row); } catch (e) { bad++; continue; }
    const h = replay(rec);
    if (!h) { bad++; continue; }
    const id = rec.ai + '|' + rec.w + '|' + JSON.stringify(rec.m);
    if (seen.has(id)) { dup++; continue; }
    seen.add(id);
    AI.setMemory({ ...AI.getMemory(), streak: 0 }); // games come from many players: no cross-game streak
    AI.learn(h, rec.ai, rec.w); used++;
  }
  const { avoid, hum } = AI.getMemory();
  const out = path.join(__dirname, '..', 'ai-book.js');
  fs.writeFileSync(out, '// generated by tools/build-book.js - do not edit\nwindow.AI_BOOK=' + JSON.stringify({ avoid, hum }) + ';\n');
  console.log(`rows ${all.length}: used ${used}, invalid ${bad}, duplicate ${dup}; seeds ${seeds.length}; avoid ${Object.keys(avoid).length}, hum ${Object.keys(hum).length} keys; ${fs.statSync(out).size} bytes -> ai-book.js`);
})().catch(e => { console.error(e.message); process.exit(1); });
